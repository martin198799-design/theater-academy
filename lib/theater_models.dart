// نموذج يمثل النص المسرحي الكامل
class PlayItem {
  final String title;
  final String author;
  final String school; // المدرسة المسرحية (شكسبير، واقعية، تعبيرية، عبث، إلخ)
  final String description;
  final String fullText;

  PlayItem({
    required this.title,
    required this.author,
    required this.school,
    required this.description,
    required this.fullText,
  });
}

// نموذج القسم
class TheaterSection {
  final String title;
  final String description;
  final List<PlayItem> plays;

  TheaterSection({
    required this.title,
    required this.description,
    required this.plays,
  });
}

